// ── Standalone present_overlay ────────────────────────────────────

bool present_overlay(int socket_fd, const uint32_t* pixels, int w, int h, float overlay_scale) {
    if (socket_fd < 0 || !pixels || w <= 0 || h <= 0) return false;

    static int s_frame_id = 0;
    ++s_frame_id;

    uint32_t fid = static_cast<uint32_t>(s_frame_id);
    uint32_t fw = static_cast<uint32_t>(w);
    uint32_t fh = static_cast<uint32_t>(h);
    size_t pixel_bytes = static_cast<size_t>(w) * h * 4;

    std::vector<uint8_t> frame_buf(OVERLAY_HEADER_SIZE + pixel_bytes);

    uint32_t magic = OVERLAY_MAGIC;
    memcpy(frame_buf.data(),      &magic,       4);
    memcpy(frame_buf.data() + 4,  &fid,         4);
    memcpy(frame_buf.data() + 8,  &fw,          4);
    memcpy(frame_buf.data() + 12, &fh,          4);
    uint32_t scale_denom = static_cast<uint32_t>(overlay_scale * 100.0f + 0.5f);
    memcpy(frame_buf.data() + 16, &scale_denom, 4);
    memcpy(frame_buf.data() + OVERLAY_HEADER_SIZE, pixels, pixel_bytes);

    const uint8_t* ptr = frame_buf.data();
    size_t remaining = frame_buf.size();
    while (remaining > 0) {
        ssize_t n = write(socket_fd, ptr, remaining);
        if (n < 0) {
            if (errno == EINTR) continue;
            if (errno == EPIPE) {
                std::cerr << "[iris] Display disconnected (Android closed connection)\n";
                return false;
            }
            if (errno == EAGAIN || errno == EWOULDBLOCK) {
                struct pollfd pfd = { socket_fd, POLLOUT, 0 };
                if (poll(&pfd, 1, 100) > 0) continue;
                std::cerr << "[iris] present_overlay write timeout (EAGAIN)\n";
                return false;
            }
            std::cerr << "[iris] present_overlay write error: " << strerror(errno) << "\n";
            return false;
        }
        if (n == 0) break;
        ptr += n;
        remaining -= n;
    }
    return true;
}

