void Canvas::clear(uint32_t color) {
#ifdef MANDELA_USE_SKIA
    if (sk_canvas_) {
        SkPaint paint;
        paint.setColor(color);
        paint.setStyle(SkPaint::kFill_Style);
        sk_canvas_->drawPaint(paint);
        return;
    }
#endif
    draw::clear(pixels_.data(), width_, height_, color);
}

void Canvas::fill_rect(int x, int y, int w, int h, uint32_t color) {
#ifdef MANDELA_USE_SKIA
    if (sk_canvas_) {
        SkPaint paint;
        paint.setColor(color);
        paint.setStyle(SkPaint::kFill_Style);
        sk_canvas_->drawRect(SkRect::MakeLTRB(x, y, x + w, y + h), paint);
        return;
    }
#endif
    draw::fill_rect(pixels_.data(), width_, height_, x, y, w, h, color);
}

void Canvas::draw_line(int x1, int y1, int x2, int y2,
                        uint32_t color, int width) {
#ifdef MANDELA_USE_SKIA
    if (sk_canvas_) {
        SkPaint paint;
        paint.setColor(color);
        paint.setStrokeWidth(width);
        paint.setStyle(SkPaint::kStroke_Style);
        paint.setAntiAlias(true);
        sk_canvas_->drawLine(x1, y1, x2, y2, paint);
        return;
    }
#endif
    draw::draw_line(pixels_.data(), width_, height_, x1, y1, x2, y2, color, width);
}

void Canvas::draw_circle(int cx, int cy, int radius,
                          uint32_t color, bool fill) {
#ifdef MANDELA_USE_SKIA
    if (sk_canvas_) {
        SkPaint paint;
        paint.setColor(color);
        paint.setAntiAlias(true);
        paint.setStyle(fill ? SkPaint::kFill_Style : SkPaint::kStroke_Style);
        sk_canvas_->drawCircle(cx, cy, radius, paint);
        return;
    }
#endif
    draw::draw_circle(pixels_.data(), width_, height_, cx, cy, radius, color, fill);
}

void Canvas::draw_text(int x, int y, const std::string& text,
                        uint32_t color, int size) {
#ifdef MANDELA_USE_SKIA
    if (sk_canvas_) {
        static sk_sp<SkTypeface> s_typeface = []() {
            auto mgr = SkFontMgr_New_FontConfig(nullptr);
            if (mgr) return mgr->matchFamilyStyle(nullptr, SkFontStyle::Normal());
            return sk_sp<SkTypeface>(nullptr);
        }();

        SkPaint paint;
        paint.setColor(color);
        paint.setAntiAlias(true);
        SkFont font(s_typeface, size);
        sk_canvas_->drawSimpleText(text.data(), text.size(),
                                    SkTextEncoding::kUTF8, x, y,
                                    font, paint);
        return;
    }
#endif
    draw::draw_text(pixels_.data(), width_, height_, x, y, text, color, size);
}

#ifdef MANDELA_USE_SKIA
void Canvas::rebuild_skia_surface() {
    if (width_ > 0 && height_ > 0 && !pixels_.empty()) {
        auto info = SkImageInfo::MakeN32Premul(width_, height_);
        sk_surface_ = SkSurfaces::WrapPixels(
            info, pixels_.data(), width_ * sizeof(uint32_t));
        if (sk_surface_)
            sk_canvas_ = sk_surface_->getCanvas();
    }
}
#endif

