Canvas::Canvas() {}

Canvas::~Canvas() {
    if (socket_fd_ >= 0) {
        close(socket_fd_);
        socket_fd_ = -1;
    }
}

bool Canvas::init(int width, int height) {
    if (width <= 0 || height <= 0) return false;
    if (width > 1920 || height > 1080) return false;

    width_ = width;
    height_ = height;
    pixels_.resize(width_ * height_, 0xFF000000);

#ifdef MANDELA_USE_SKIA
    auto info = SkImageInfo::MakeN32Premul(width_, height_);
    sk_surface_ = SkSurfaces::WrapPixels(
        info, pixels_.data(), width_ * sizeof(uint32_t));
    if (sk_surface_)
        sk_canvas_ = sk_surface_->getCanvas();
#endif

    return true;
}

void Canvas::load_frame(const uint8_t* bgra_data, size_t size) {
    size_t expected = static_cast<size_t>(width_) * height_ * 4;
    if (size != expected) return;
    if (!bgra_data) return;
    std::memcpy(pixels_.data(), bgra_data, size);
}

// ── Socket overlay ────────────────────────────────────────────────

bool Canvas::connect_overlay(const std::string& socket_name) {
    if (socket_fd_ >= 0) {
        close(socket_fd_);
        socket_fd_ = -1;
    }

    socket_fd_ = socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC, 0);
    if (socket_fd_ < 0) {
        std::cerr << "[iris] socket() failed: " << strerror(errno) << "\n";
        return false;
    }

    int sndbuf = 2 * 1024 * 1024;
    setsockopt(socket_fd_, SOL_SOCKET, SO_SNDBUF, &sndbuf, sizeof(sndbuf));

    struct sockaddr_un addr;
    std::memset(&addr, 0, sizeof(addr));
    addr.sun_family = AF_UNIX;

    size_t name_len = socket_name.size();
    if (name_len > sizeof(addr.sun_path) - 1)
        name_len = sizeof(addr.sun_path) - 1;
    std::memcpy(addr.sun_path + 1, socket_name.data(), name_len);

    socklen_t addr_len = offsetof(struct sockaddr_un, sun_path) + 1 + name_len;

    if (::connect(socket_fd_, (struct sockaddr*)&addr, addr_len) < 0) {
        std::cerr << "[iris] connect('" << socket_name << "') failed: "
                  << strerror(errno) << "\n";
        close(socket_fd_);
        socket_fd_ = -1;
        return false;
    }

    socket_name_ = socket_name;
    std::cerr << "[iris] Connected to overlay '" << socket_name_ << "'\n";
    return true;
}

bool Canvas::present() {
    if (socket_fd_ < 0) return false;
    if (width_ <= 0 || height_ <= 0) return false;

    ++frame_id_;

    uint32_t fid = static_cast<uint32_t>(frame_id_);
    uint32_t w   = static_cast<uint32_t>(width_);
    uint32_t h   = static_cast<uint32_t>(height_);
    size_t pixel_bytes = static_cast<size_t>(w) * h * 4;

    std::vector<uint8_t> frame_buf(OVERLAY_HEADER_SIZE + pixel_bytes);

    uint32_t magic = OVERLAY_MAGIC;
    memcpy(frame_buf.data(),      &magic,        4);
    memcpy(frame_buf.data() + 4,  &fid,          4);
    memcpy(frame_buf.data() + 8,  &w,            4);
    memcpy(frame_buf.data() + 12, &h,            4);
    uint32_t scale_denom = static_cast<uint32_t>(overlay_scale_ * 100.0f + 0.5f);
    memcpy(frame_buf.data() + 16, &scale_denom,  4);
    memcpy(frame_buf.data() + OVERLAY_HEADER_SIZE, pixels_.data(), pixel_bytes);

    const uint8_t* ptr = frame_buf.data();
    size_t remaining = frame_buf.size();
    while (remaining > 0) {
        ssize_t n = write(socket_fd_, ptr, remaining);
        if (n < 0) {
            if (errno == EINTR) continue;
            if (errno == EPIPE) {
                std::cerr << "[iris] Display disconnected (Android closed connection)\n";
                close(socket_fd_);
                socket_fd_ = -1;
                return false;
            }
            if (errno == EAGAIN || errno == EWOULDBLOCK) {
                struct pollfd pfd = { socket_fd_, POLLOUT, 0 };
                if (poll(&pfd, 1, 100) > 0) continue;
                std::cerr << "[iris] Socket write timeout (EAGAIN)\n";
                return false;
            }
            std::cerr << "[iris] Socket write error: " << strerror(errno) << "\n";
            break;
        }
        if (n == 0) break;
        ptr += n;
        remaining -= n;
    }
    return true;
}

